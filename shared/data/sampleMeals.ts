/**
 * Ukážkové recepty na raňajky, desiatu, olovrant a večeru – typická slovenská kuchyňa, jednoduché a rýchle. Sú to
 * údaje (po slovensky), nie texty aplikácie. `key` je trvalý (podľa neho sa recept nájde pri doplnení či odstránení).
 */
type Ing = NonNullable<RecipeInputRaw['ingredients']>[number]
type Step = NonNullable<RecipeInputRaw['steps']>[number]

export type MealSampleSet = 'ranajky' | 'desiata' | 'olovrant' | 'vecera'
export interface MealSample extends RecipeInputRaw {
  key: string
  set: MealSampleSet
  category: RecipeCategory
  alsoCategories: RecipeCategory[]
}

const i = (
  name: string,
  quantity: number | null,
  unit: Ing['unit'] = null,
  extra: Partial<Ing> = {},
): Ing => ({ name, quantity, unit, ...extra })
const opt = (name: string, quantity: number | null, unit: Ing['unit'] = null, note?: string): Ing =>
  i(name, quantity, unit, { isOptional: true, ...(note ? { note } : {}) })
const s = (text: string, timerMinutes?: number): Step =>
  timerMinutes ? { text, timerSeconds: timerMinutes * 60 } : { text }

